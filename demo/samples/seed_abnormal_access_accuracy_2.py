def main() -> None:
    out = Path(__file__).parent / "accuracy2"
    out.mkdir(parents=True, exist_ok=True)
    workbook = Workbook()
    sheet = workbook.active
    sheet.title = "异常访问记录"
    sheet.append(HEADERS)
    ground: list[dict] = []
    for row in ROWS:
        seq, ts, ip, owner, target, port, event, behavior, reqs, keep, category = row
        sheet.append([seq, ts, ip, owner, target, port, event, behavior, reqs])
        tricky = seq >= 25
        ground.append({
            "seq": seq,
            "expected": "keep" if keep else "filter",
            "category": category if keep else "low-risk",
            "tricky": tricky,
        })
    workbook.save(out / "abnormal-access-complex-2.xlsx")
    (out / "abnormal-access-complex-2.ground-truth.json").write_text(
        json.dumps({"headers": HEADERS, "records": ground}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"wrote {out} ({len(ROWS)} records; keep={sum(1 for r in ROWS if r[9])})")


if __name__ == "__main__":
    main()
